export function matchBrandToProduct(
  brand: FamousBrand,
  product: { brandId?: string; brand: string; nameAr: string; nameEn?: string }
): boolean {
  if (product.brandId && product.brandId === brand.id) return true;
  const haystack = `${product.brand} ${product.nameAr} ${product.nameEn || ''}`.toLowerCase();
  return brand.matchKeywords.some((kw) => haystack.includes(kw.toLowerCase()));
}
